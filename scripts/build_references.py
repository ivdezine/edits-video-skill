#!/usr/bin/env python3
"""Regenerate references/tool-reference.md and references/catalogs.md from the live server.

The editor tool set only appears while a project is open, so this opens a project,
reads tools/list, and closes it again. It never edits the project.

    build_references.py --project-id <uuid>      # project to open read-only
    build_references.py --tools-json <file>      # or build from a saved tools/list dump
    build_references.py --catalogs-only          # catalogs only (works on the home screen)
"""
import argparse, collections, json, os, re, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mcp_client import Client

REF = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "references")
ORDER = ["home screen only", "navigation", "playback", "inspection", "analysis", "editing", "tools", "text", "captions",
         "color", "audio", "voiceover", "tts", "media", "ai", "export", "zoom", "settings",
         "automation", "utility"]


def clean(s):
    return re.sub(r"\s+", " ", (s or "").replace("\u2014", " - ").replace("|", "/")).strip()


def tool_reference(tools, home_tools):
    home_names = {t["name"] for t in home_tools}
    editor_names = {t["name"] for t in tools}
    home_only = [t for t in home_tools if t["name"] not in editor_names]
    cats = collections.defaultdict(list)
    for t in home_only:
        cats["home screen only"].append(t)
    for t in tools:
        d = t.get("description") or ""
        m = re.search(r"\[([^\]]+)\]\s*$", d)
        cats[m.group(1) if m else "other"].append(t)
    lines = ["# Edits tool reference", "",
             "Generated by `scripts/build_references.py` from the live `tools/list`: %d editor tools, "
             "plus %d that exist only on the home screen." % (len(tools), len(home_only)),
             "Descriptions are Meta's own text, quoted verbatim, so their spelling is left as written.",
             "Params marked `*` are listed as required by the schema, which is not reliable: "
             "alternatives (id or name, id or path) are both marked required. Read the description.",
             "Tools marked (home) also exist on the home screen.", ""]
    keys = [k for k in ORDER if k in cats] + sorted(k for k in cats if k not in ORDER)
    for k in keys:
        lines += ["## %s (%d)" % (k, len(cats[k])), ""]
        for t in sorted(cats[k], key=lambda x: x["name"]):
            s = t.get("inputSchema", {})
            req = set(s.get("required", []))
            ann = t.get("annotations", {})
            flags = []
            if ann.get("readOnlyHint"): flags.append("read-only")
            if ann.get("destructiveHint"): flags.append("DESTRUCTIVE")
            if t["name"] in home_names: flags.append("home")
            desc = clean(re.sub(r"\s*\[[^\]]+\]\s*$", "", t.get("description") or ""))
            lines.append("### `%s`%s" % (t["name"], (" (" + ", ".join(flags) + ")") if flags else ""))
            lines.append(desc)
            for p, v in s.get("properties", {}).items():
                typ = v.get("type", "")
                enum = (" one of " + "/".join(map(str, v["enum"]))) if v.get("enum") else ""
                pd = clean(v.get("description"))
                lines.append("- `%s%s` %s%s%s" % (p, "*" if p in req else "", typ, enum, (": " + pd) if pd else ""))
            lines.append("")
    return "\n".join(lines)


def catalogs(c):
    kinds = c.tool("listCatalogKinds")
    kinds = kinds.get("kinds", kinds)
    out = ["# Edits catalogs", "",
           "Generated by `scripts/build_references.py` via `listCatalog`. Apply an item with its "
           "`applyTool`, passing the item `id` as `applyParam`. Ids are stable strings; display names are not.", ""]
    for k in kinds:
        kind = k["kind"] if isinstance(k, dict) else k
        items, cursor = [], None
        while True:
            args = {"kind": kind, "limit": 200}
            if cursor: args["cursor"] = cursor
            r = c.tool("listCatalog", args)
            items += r.get("items", [])
            cursor = r.get("nextCursor")
            if not cursor: break
        head = items[0] if items else {}
        out += ["## %s (%d)" % (kind, len(items)), "",
                "Apply with `%s`, param `%s`. Applies to: %s." % (
                    head.get("applyTool", k.get("applyTool", "?") if isinstance(k, dict) else "?"),
                    head.get("applyParam", k.get("applyParam", "?") if isinstance(k, dict) else "?"),
                    ", ".join(k.get("appliesTo", [])) if isinstance(k, dict) else "?"), ""]
        params = {}
        for it in items:
            ps = it.get("paramSchema") or {}
            if ps: params[json.dumps(ps, sort_keys=True)] = ps
        if params:
            out.append("Item params seen: " + "; ".join(
                ", ".join("%s (%s, default %s)" % (n, s.get("type"), s.get("default")) for n, s in p.items())
                for p in params.values()))
            out.append("")
        out.append("| id | display name |")
        out.append("|---|---|")
        for it in items:
            out.append("| `%s` | %s%s |" % (it.get("id"), clean(it.get("displayName")),
                                            " (none / clears)" if it.get("isNone") else ""))
        out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--project-id")
    ap.add_argument("--tools-json")
    ap.add_argument("--home-tools-json")
    ap.add_argument("--catalogs-only", action="store_true")
    a = ap.parse_args()
    c = Client()
    home = c.list_tools() if c.tool("appState").get("screen") == "home" else []
    if a.home_tools_json:
        home = json.load(open(a.home_tools_json))["result"]["tools"]
    open(os.path.join(REF, "catalogs.md"), "w").write(catalogs(c))
    print("wrote catalogs.md")
    if a.catalogs_only:
        return
    if a.tools_json:
        tools = json.load(open(a.tools_json))["result"]["tools"]
    elif a.project_id:
        c.tool("openProject", {"id": a.project_id})
        for _ in range(40):
            if c.tool("appState").get("screen") == "editor": break
            time.sleep(0.25)
        tools = c.list_tools()
        c.tool("closeProject")
    else:
        sys.exit("pass --project-id or --tools-json (or --catalogs-only)")
    open(os.path.join(REF, "tool-reference.md"), "w").write(tool_reference(tools, home))
    print("wrote tool-reference.md (%d tools)" % len(tools))


if __name__ == "__main__":
    main()
